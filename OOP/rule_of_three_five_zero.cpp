// Rule of zero, three, and five
//
// Rule of zero: if a class does not manage a resource directly, write no
// destructor, copy constructor, copy assignment, move constructor, or move
// assignment. The compiler-generated versions are correct.
//
// Rule of three: if a class needs any one of
//   destructor, copy constructor, copy assignment
// it usually needs all three (see 16_copy_semantics.cpp).
//
// Rule of five: with move semantics, add
//   move constructor and move assignment
// so the resource can be transferred instead of copied.
//
// This file shows a hand-written rule-of-five class and the same behavior
// written with standard containers (rule of zero).

#include <iostream>
#include <string>
#include <utility>
#include <vector>
using namespace std;

class IntArray {
    int *data;
    int size;

   public:
    IntArray(int count) {
        size = count;
        data = new int[size];

        for (int i = 0; i < size; i++) {
            data[i] = 0;
        }
    }

    // 1. Destructor
    ~IntArray() {
        delete[] data;
    }

    // 2. Copy constructor
    IntArray(const IntArray &other) {
        size = other.size;
        data = new int[size];

        for (int i = 0; i < size; i++) {
            data[i] = other.data[i];
        }
    }

    // 3. Copy assignment
    IntArray &operator=(const IntArray &other) {
        if (this == &other) {
            return *this;
        }

        delete[] data;

        size = other.size;
        data = new int[size];

        for (int i = 0; i < size; i++) {
            data[i] = other.data[i];
        }

        return *this;
    }

    // 4. Move constructor: steal the pointer, leave the source empty.
    IntArray(IntArray &&other) noexcept {
        data = other.data;
        size = other.size;

        other.data = nullptr;
        other.size = 0;
    }

    // 5. Move assignment
    IntArray &operator=(IntArray &&other) noexcept {
        if (this == &other) {
            return *this;
        }

        delete[] data;

        data = other.data;
        size = other.size;

        other.data = nullptr;
        other.size = 0;

        return *this;
    }

    void set(int index, int value) {
        data[index] = value;
    }

    int get(int index) const {
        return data[index];
    }

    int length() const {
        return size;
    }
};

// Rule of zero: vector handles allocation, copying, moving, and destruction.
class ModernArray {
    vector<int> data;

   public:
    ModernArray(int count) : data(count, 0) {}

    void set(int index, int value) {
        data[index] = value;
    }

    int get(int index) const {
        return data[index];
    }

    int length() const {
        return data.size();
    }
};

// A factory returning by value uses the move constructor (or copy elision).
IntArray makeArray() {
    IntArray result(3);
    result.set(0, 7);
    result.set(1, 8);
    result.set(2, 9);
    return result;
}

int main() {
    IntArray first(3);
    first.set(0, 1);
    first.set(1, 2);
    first.set(2, 3);

    IntArray copied = first;  // copy constructor
    copied.set(0, 100);

    cout << first.get(0) << " " << copied.get(0) << endl;  // 1 100

    IntArray assigned(1);
    assigned = first;                 // copy assignment
    cout << assigned.get(2) << endl;  // 3

    IntArray moved = std::move(first);  // move constructor
    cout << moved.get(0) << endl;       // 1
    cout << first.length() << endl;     // 0 (moved-from object is empty)

    IntArray fromFactory = makeArray();
    cout << fromFactory.get(2) << endl;  // 9

    ModernArray modern(3);
    modern.set(0, 42);
    ModernArray modernCopy = modern;    // deep copy, generated by the compiler
    cout << modernCopy.get(0) << endl;  // 42

    return 0;
}

// Special cases:
//   - a moved-from object must be left in a valid but unspecified state; the
//     class above chooses "empty"
//   - mark move operations `noexcept`, otherwise vector reallocation will copy
//     instead of move
//   - the compiler deletes the move operations if a destructor or copy
//     operation is user-declared (unless you declare them)
//   - copy elision can skip the move constructor entirely (C++17 guarantees
//     it in some cases)
//   - the best rule is zero: use `vector`, `string`, `unique_ptr`, and
//     `shared_ptr` instead of raw owning pointers
